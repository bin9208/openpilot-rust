//! Python-free DBC composition and declarative fixed radar schemas.
//! Fixed script outputs are data, pinned to source inputs and verified bytewise.
use super::identity;
use serde::Deserialize;
use sha2::{Digest, Sha256};
use std::{
    collections::BTreeMap,
    fs,
    path::{Component, Path},
};
type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;
#[derive(Deserialize)]
struct Record {
    sha256: String,
}
#[derive(Deserialize)]
struct Fixture {
    source_commit: String,
    inputs: BTreeMap<String, Record>,
    fixed_schemas: BTreeMap<String, String>,
    generated_sha256: BTreeMap<String, String>,
}
fn compose(filename: &str, text: &str, files: &BTreeMap<String, String>) -> Result<String> {
    let mut includes = Vec::new();
    let mut core = String::new();
    let mut remaining = text;
    while let Some(start) = remaining.find("CM_ \"IMPORT ") {
        let begin = start + "CM_ \"IMPORT ".len();
        let Some(end) = remaining[begin..].find("\";\n") else {
            break;
        };
        let name = &remaining[begin..begin + end];
        if Path::new(name)
            .components()
            .any(|c| !matches!(c, Component::Normal(_)))
        {
            return Err("invalid DBC import path".into());
        }
        includes.push(name);
        core.push_str(&remaining[..start]);
        remaining = &remaining[begin + end + 3..];
    }
    core.push_str(remaining);
    let mut output = String::from("CM_ \"AUTOGENERATED FILE, DO NOT EDIT\";\n");
    let parent = Path::new(filename)
        .parent()
        .ok_or("DBC source has no parent")?;
    for name in includes {
        output.push_str(&format!("\n\nCM_ \"Imported file {name} starts here\";\n"));
        output.push_str(
            files
                .get(parent.join(name).to_str().ok_or("DBC path encoding")?)
                .ok_or("DBC import missing")?,
        );
    }
    let name = Path::new(filename)
        .file_name()
        .and_then(|v| v.to_str())
        .ok_or("DBC filename")?;
    output.push_str(&format!("\nCM_ \"{name} starts here\";\n"));
    output.push_str(&core);
    Ok(output)
}
pub fn generate(source: &Path) -> Result<BTreeMap<String, String>> {
    let fixture: Fixture =
        serde_json::from_str(include_str!("../../../../upstream/dbc-generators.json"))?;
    if fixture.source_commit != identity::UPSTREAM {
        return Err("DBC upstream pin differs".into());
    }
    let mut files = BTreeMap::new();
    for (name, record) in &fixture.inputs {
        let path = source.join(name);
        // Original scripts are provenance only. Native generation does not need
        // Python source present, but a changed retained script cannot go unnoticed.
        if name.ends_with(".py") && !path.exists() {
            continue;
        }
        if identity::file_hash(&path)? != record.sha256 {
            return Err(format!("DBC source differs from pinned schema: {name}").into());
        }
        if name.ends_with(".dbc") {
            files.insert(name.clone(), fs::read_to_string(path)?);
        }
    }
    files.extend(fixture.fixed_schemas);
    let mut output = BTreeMap::new();
    for (name, contents) in &files {
        let path = Path::new(name);
        let filename = path
            .file_name()
            .and_then(|v| v.to_str())
            .ok_or("DBC filename")?;
        if path.components().count() == 1 {
            if !fixture.generated_sha256.contains_key(filename) {
                output.insert(filename.to_owned(), contents.clone());
            }
        } else if name.starts_with("generator/") && !filename.starts_with('_') {
            let target = filename.replace(".dbc", "_generated.dbc");
            let result = compose(name, contents, &files)?;
            let expected = fixture
                .generated_sha256
                .get(&target)
                .ok_or("unverified generated DBC")?;
            if format!("{:x}", Sha256::digest(result.as_bytes())) != *expected {
                return Err(format!("native/source DBC generation differs: {target}").into());
            }
            output.insert(target, result);
        }
    }
    if !fixture
        .generated_sha256
        .keys()
        .all(|name| output.contains_key(name))
    {
        return Err("generated DBC absent".into());
    }
    Ok(output)
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn imports_preserve_order_whitespace_and_one_level_source_semantics() {
        let files = BTreeMap::from([
            ("generator/car/_a.dbc".into(), "A\n".into()),
            ("generator/car/_b.dbc".into(), "B\n".into()),
        ]);
        assert_eq!(compose("generator/car/car.dbc", "first\nCM_ \"IMPORT _b.dbc\";\nCM_ \"IMPORT _a.dbc\";\nlast\n", &files).unwrap(), "CM_ \"AUTOGENERATED FILE, DO NOT EDIT\";\n\n\nCM_ \"Imported file _b.dbc starts here\";\nB\n\n\nCM_ \"Imported file _a.dbc starts here\";\nA\n\nCM_ \"car.dbc starts here\";\nfirst\nlast\n");
    }
    #[test]
    fn complete_pinned_source_generation_matches_all_reference_hashes() {
        let source =
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../opendbc_repo/opendbc/dbc");
        let schemas = generate(&source).unwrap();
        assert!(schemas.len() > 100);
        assert!(schemas.contains_key("hyundai_canfd_corner_radar_235_generated.dbc"));
        assert!(schemas.contains_key("tesla_radar_bosch_generated.dbc"));
    }
}
