//! C++ service headers from the same Rust catalog used by native messaging.
use crate::seal::Result;
use serde::Serialize;
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use std::{
    fs,
    io::{self, Write},
    path::PathBuf,
};
#[derive(Serialize)]
pub struct Service {
    name: &'static str,
    should_log: bool,
    frequency: f64,
    decimation: Option<u32>,
    queue_size: usize,
    frequency_range: Option<(f64, f64)>,
}
include!("../../messaging/src/services_generated.rs");
/// Complete tuples, including frequency ranges not represented in C++ headers.
pub fn catalog() -> Value {
    serde_json::to_value(SERVICES).expect("static service catalog serializes")
}
/// Script mode preserves the extra newline from the old `print(build_header())`.
pub fn header(script_newline: bool) -> String {
    let mut out=String::from("/* THIS IS AN AUTOGENERATED FILE, PLEASE EDIT services.py */\n#ifndef __SERVICES_H\n#define __SERVICES_H\n#include <map>\n#include <string>\nstruct service { std::string name; bool should_log; float frequency; int decimation; size_t queue_size; };\nstatic std::map<std::string, service> services = {\n");
    for service in SERVICES {
        out.push_str(&format!(
            "  {{ \"{}\", {{\"{}\", {}, {:.6}, {}, {}}}}},\n",
            service.name,
            service.name,
            service.should_log,
            service.frequency,
            service.decimation.map(i64::from).unwrap_or(-1),
            service.queue_size
        ));
    }
    out.push_str("};\n#endif\n");
    if script_newline {
        out.push('\n');
    }
    out
}
/// Fingerprint the sources compiled into this executable, not a mutable checkout.
pub fn provenance(script_newline: bool) -> Value {
    json!({
        "source_sha256": {
            "rust/crates/dev-tools/src/services_header.rs": format!("{:x}",Sha256::digest(include_bytes!("services_header.rs"))),
            "rust/crates/messaging/src/services_generated.rs": format!("{:x}",Sha256::digest(include_bytes!("../../messaging/src/services_generated.rs")))
        },
        "header_sha256": format!("{:x}",Sha256::digest(header(script_newline).as_bytes()))
    })
}
pub fn cli() -> Result<()> {
    let mut args = std::env::args_os().skip(1);
    let mut output = None;
    let mut script = false;
    while let Some(arg) = args.next() {
        match arg.to_str() {
            Some("--output") => {
                if output.is_some() {
                    return Err("duplicate --output".into());
                }
                output = Some(PathBuf::from(
                    args.next().ok_or("--output requires a value")?,
                ));
            }
            Some("--script-newline") => script = true,
            Some("--help" | "-h") => {
                println!("Usage: generate-services-header [--output FILE] [--script-newline]");
                return Ok(());
            }
            _ => return Err("unknown services header argument".into()),
        }
    }
    let content = header(script);
    if let Some(path) = output {
        fs::write(path, content)?;
    } else {
        io::stdout().lock().write_all(content.as_bytes())?;
    }
    Ok(())
}
