//! Rebuild the Bluetooth digit tables from pinned Unicode data, without Python.
use crate::seal::Result;
use sha2::{Digest, Sha256};
use std::{collections::BTreeSet, fmt::Write};

pub fn generate() -> Result<String> {
    let data = include_str!("../data/unicode-15.0.0/DerivedNumericType.txt");
    if format!("{:x}", Sha256::digest(data.as_bytes()))
        != "710abf2d581ac9c57f244c0834f9d9969d9781e0396adccd330eaae658ac7d6b"
    {
        return Err("Unicode 15.0.0 numeric properties changed".into());
    }
    let mut digits = BTreeSet::new();
    let mut decimal = BTreeSet::new();
    for line in data.lines() {
        let fields = line.split('#').next().unwrap().trim();
        if fields.is_empty() {
            continue;
        }
        let (range, property) = fields.split_once(';').ok_or("missing Unicode property")?;
        let property = property.trim();
        if !matches!(property, "Digit" | "Decimal") {
            continue;
        }
        let range = range.trim();
        let (low, high) = range.split_once("..").unwrap_or((range, range));
        let low = u32::from_str_radix(low, 16)?;
        let high = u32::from_str_radix(high, 16)?;
        if low > high || high > 0x10ffff {
            return Err("invalid Unicode numeric range".into());
        }
        digits.extend(low..=high);
        if property == "Decimal" {
            if (high - low + 1) % 10 != 0 {
                return Err("decimal digits do not form ten-digit sequences".into());
            }
            decimal.extend((low..=high).step_by(10));
        }
    }
    let mut ranges: Vec<(u32, u32)> = vec![];
    for point in digits {
        match ranges.last_mut() {
            Some((_, high)) if *high + 1 == point => *high = point,
            _ => ranges.push((point, point)),
        }
    }
    // Preserve the original generator's byte output, including its provenance.
    let mut output = String::from("// Generated by rust/tools/generate_bluetooth_digits.py from CPython Unicode 15.0.0.\npub(super) const DIGITS: &[(u32, u32)] = &[\n");
    for (low, high) in ranges {
        writeln!(output, "    (0x{low:x}, 0x{high:x}),")?;
    }
    output.push_str("];\n\npub(super) const DECIMAL: &[u32] = &[\n");
    let decimal = decimal.into_iter().collect::<Vec<_>>();
    for row in decimal.chunks(8) {
        output.push_str("    ");
        for (index, point) in row.iter().enumerate() {
            if index > 0 {
                output.push_str(", ");
            }
            write!(output, "0x{point:x}")?;
        }
        output.push_str(",\n");
    }
    output.push_str("];\n");
    Ok(output)
}
