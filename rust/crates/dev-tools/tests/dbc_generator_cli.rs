#[test]
fn actual_stage_keeps_existing_file_directory_and_second_run_is_noop() {
    let temp = tempfile::tempdir().unwrap();
    let output = temp.path();
    let baseline = fixture();
    let identities = baseline["outputs"].as_object().unwrap();
    let names: Vec<_> = identities.keys().collect();
    let preserved = output.join(format!("{}.dbc", names[0]));
    let directory = output.join(format!("{}.dbc", names[1]));
    fs::write(&preserved, b"EXISTING CORRUPT CONTENT MUST SURVIVE").unwrap();
    fs::create_dir(&directory).unwrap();
    let args = ["--root".as_ref(), output.as_os_str()];
    let report: Value = serde_json::from_slice(&success(run(
        env!("CARGO_BIN_EXE_stage-control-dbcs"),
        &args,
    )))
    .unwrap();
    assert_eq!(report["added"].as_object().unwrap().len(), 43);
    assert_eq!(report["existing_files"], "preserved");
    assert_eq!(
        fs::read(&preserved).unwrap(),
        b"EXISTING CORRUPT CONTENT MUST SURVIVE"
    );
    assert!(directory.is_dir());
    for name in names.into_iter().skip(2) {
        let bytes = fs::read(output.join(format!("{name}.dbc"))).unwrap();
        assert_eq!(
            format!("{:x}", Sha256::digest(&bytes)),
            identities[name]["sha256"].as_str().unwrap()
        );
    }
    let second: Value = serde_json::from_slice(&success(run(
        env!("CARGO_BIN_EXE_stage-control-dbcs"),
        &args,
    )))
    .unwrap();
    assert_eq!(second, json!({"added":{},"existing_files":"preserved"}));
}
#[test]
fn actual_compose_raw_path_partial_failure_and_native_usage_exit() {
    #[cfg(not(target_os = "macos"))]
    use std::os::unix::ffi::OsStringExt;
    let temp = tempfile::tempdir().unwrap();
    #[cfg(not(target_os = "macos"))]
    let source = temp
        .path()
        .join(std::ffi::OsString::from_vec(b"source-\xff".to_vec()));
    // APFS requires UTF-8 filenames; exercise a non-ASCII path without raw FF.
    // https://developer.apple.com/library/archive/documentation/FileManagement/Conceptual/APFS_Guide/FAQ/FAQ.html
    #[cfg(target_os = "macos")]
    let source = temp.path().join("source-한");
    let output = temp.path().join("output");
    fs::create_dir(&source).unwrap();
    fs::create_dir(&output).unwrap();
    fs::write(source.join("car.dbc"), b"CM_ \"IMPORT missing.dbc\";\nCORE").unwrap();
    let result = run(
        env!("CARGO_BIN_EXE_dbc-generator"),
        &[
            "compose".as_ref(),
            source.as_os_str(),
            "car.dbc".as_ref(),
            output.as_os_str(),
        ],
    );
    assert_eq!(result.status.code(), Some(1));
    assert!(result.stdout.is_empty());
    assert!(String::from_utf8_lossy(&result.stderr).starts_with("FileNotFoundError:"));
    assert_eq!(fs::read(output.join("car_generated.dbc")).unwrap(),b"CM_ \"AUTOGENERATED FILE, DO NOT EDIT\";\n\n\nCM_ \"Imported file missing.dbc starts here\";\n");
    #[cfg(target_os = "macos")]
    {
        // Invalid file contents are still valid APFS fixtures. Keep both original
        // decode failures and their exact partial output bytes in the common CLI.
        for case in error_fixture().as_array().unwrap().iter().filter(|case| {
            matches!(
                case["name"].as_str(),
                Some("invalid-main-utf8" | "invalid-include-utf8")
            )
        }) {
            let temp = tempfile::tempdir().unwrap();
            let source = temp.path().join("source-한");
            let output = temp.path().join("output");
            fs::create_dir(&source).unwrap();
            fs::create_dir(&output).unwrap();
            for pair in case["inputs"].as_array().unwrap() {
                let filename = String::from_utf8(unhex(pair[0].as_str().unwrap())).unwrap();
                fs::write(source.join(filename), unhex(pair[1].as_str().unwrap())).unwrap();
            }
            let result = run(
                env!("CARGO_BIN_EXE_dbc-generator"),
                &[
                    "--json-errors".as_ref(),
                    "compose".as_ref(),
                    source.as_os_str(),
                    "car.dbc".as_ref(),
                    output.as_os_str(),
                ],
            );
            assert_eq!(result.status.code(), Some(1));
            assert!(result.stdout.is_empty());
            let actual: Value = serde_json::from_slice(&result.stderr).unwrap();
            assert_eq!(actual["kind"], case["error"]["kind"]);
            assert_eq!(actual["errno"], case["error"]["errno"]);
            assert_eq!(
                actual["decode_bytes"],
                json!(unhex(case["error"]["decode_hex"].as_str().unwrap()))
            );
            let expected = case["outputs"].as_object().unwrap();
            assert_eq!(fs::read_dir(&output).unwrap().count(), expected.len());
            for (name, bytes) in expected {
                let filename = String::from_utf8(unhex(name)).unwrap();
                assert_eq!(
                    fs::read(output.join(filename)).unwrap(),
                    unhex(bytes.as_str().unwrap())
                );
            }
        }
    }
    for binary in [
        env!("CARGO_BIN_EXE_dbc-generator"),
        env!("CARGO_BIN_EXE_stage-control-dbcs"),
    ] {
        let result = run(binary, &["--unknown".as_ref()]);
        assert_eq!(result.status.code(), Some(2));
        assert!(result.stdout.is_empty());
        assert!(!success(run(binary, &["--help".as_ref()])).is_empty());
    }
    let names: Vec<String> = serde_json::from_slice(&success(run(
        env!("CARGO_BIN_EXE_dbc-generator"),
        &["program-outputs".as_ref()],
    )))
    .unwrap();
    assert_eq!(names.len(), 10);
    let baseline = fixture();
    for name in names {
        assert!(baseline["outputs"]
            .get(name.strip_suffix(".dbc").unwrap())
            .is_some());
    }
}

fn copy_source(source: &Path, target: &Path) {
    fs::create_dir(target).unwrap();
    for entry in fs::read_dir(source).unwrap() {
        let entry = entry.unwrap();
        let from = entry.path();
        let to = target.join(entry.file_name());
        if from.is_dir() {
            copy_source(&from, &to);
        } else {
            fs::copy(from, to).unwrap();
        }
    }
}
#[test]
fn actual_complete_in_place_all_programs_works_without_retired_files_or_rivian_directory() {
    let temp = tempfile::tempdir().unwrap();
    let source = temp.path().join("generator");
    let output = temp.path().join("output");
    fs::create_dir(&output).unwrap();
    copy_source(&root().join("opendbc_repo/opendbc/dbc/generator"), &source);
    // A fresh Git checkout after retirement contains neither Python files nor
    // Rivian's formerly Python-only directory. Retained DBC templates are real.
    fn remove_python(path: &Path) {
        for entry in fs::read_dir(path).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                remove_python(&path);
            } else if path.extension().is_some_and(|v| v == "py") {
                fs::remove_file(path).unwrap();
            }
        }
    }
    remove_python(&source);
    if source.join("rivian").exists() {
        fs::remove_dir_all(source.join("rivian")).unwrap();
    }
    fs::write(output.join("old_generated.dbc"), b"STALE").unwrap();
    let args = [
        "create-all".as_ref(),
        output.as_os_str(),
        "--source".as_ref(),
        source.as_os_str(),
        "--all-programs".as_ref(),
    ];
    assert!(success(run(env!("CARGO_BIN_EXE_dbc-generator"), &args)).is_empty());
    assert!(!output.join("old_generated.dbc").exists());
    let baseline = fixture();
    let mut identities = serde_json::Map::new();
    for entry in fs::read_dir(&output).unwrap() {
        let path = entry.unwrap().path();
        let bytes = fs::read(&path).unwrap();
        identities.insert(
            path.file_stem().unwrap().to_str().unwrap().to_owned(),
            json!({"bytes":bytes.len(),"sha256":format!("{:x}",Sha256::digest(bytes))}),
        );
    }
    assert_eq!(Value::Object(identities), baseline["outputs"]);
    assert!(source.join("rivian/rivian_mando_front_radar.dbc").is_file());
    assert!(source
        .join("chrysler/_stellantis_common_ram_dt_generated.dbc")
        .is_file());
    assert!(source
        .join("chrysler/_stellantis_common_ram_hd_generated.dbc")
        .is_file());
    let result = run(
        env!("CARGO_BIN_EXE_dbc-generator"),
        &[
            "create-all".as_ref(),
            output.as_os_str(),
            "--source".as_ref(),
            source.as_os_str(),
            "--all-programs".as_ref(),
            "--program".as_ref(),
            "chrysler-ram".as_ref(),
        ],
    );
    assert_eq!(result.status.code(), Some(2));
    assert!(result.stdout.is_empty());
    assert!(String::from_utf8_lossy(&result.stderr).contains("cannot be mixed"));
}

fn unhex(text: &str) -> Vec<u8> {
    text.as_bytes()
        .chunks_exact(2)
        .map(|pair| u8::from_str_radix(std::str::from_utf8(pair).unwrap(), 16).unwrap())
        .collect()
}
