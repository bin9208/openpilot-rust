//! Native CLI plumbing; output expectations remain independent original bytes.
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use std::{
    fs,
    path::{Path, PathBuf},
    process::{Command, Output},
};
fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..")
}
fn fixture() -> Value {
    serde_json::from_slice(
        &fs::read(
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("tests/fixtures/dbc-generator/generate-all-original.json"),
        )
        .unwrap(),
    )
    .unwrap()
}
fn run(binary: &str, args: &[&std::ffi::OsStr]) -> Output {
    Command::new(binary)
        .args(args)
        .env("PATH", "")
        .env("OPENPILOT_RUST_ROOT", root())
        .output()
        .unwrap()
}
fn success(output: Output) -> Vec<u8> {
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(
        output.stderr.is_empty(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    output.stdout
}
