// APFS cannot create this corpus's raw-byte filenames (Apple APFS FAQ above).
#[cfg(target_os = "linux")]
#[test]
fn json_error_boundary_retains_original_io_and_unicode_raw_objects_and_partial_outputs() {
    use std::os::unix::ffi::{OsStrExt, OsStringExt};
    let cases = error_fixture();
    assert_eq!(cases.as_array().unwrap().len(), 4);
    for case in cases.as_array().unwrap() {
        let temp = tempfile::tempdir().unwrap();
        let source = temp.path().join(std::ffi::OsString::from_vec(unhex(
            case["source_hex"].as_str().unwrap(),
        )));
        let output = temp.path().join("output");
        let filename = std::ffi::OsString::from_vec(unhex(case["filename_hex"].as_str().unwrap()));
        fs::create_dir(&source).unwrap();
        fs::create_dir(&output).unwrap();
        for pair in case["inputs"].as_array().unwrap() {
            fs::write(
                source.join(std::ffi::OsString::from_vec(unhex(
                    pair[0].as_str().unwrap(),
                ))),
                unhex(pair[1].as_str().unwrap()),
            )
            .unwrap();
        }
        let result = run(
            env!("CARGO_BIN_EXE_dbc-generator"),
            &[
                "--json-errors".as_ref(),
                "compose".as_ref(),
                source.as_os_str(),
                filename.as_os_str(),
                output.as_os_str(),
            ],
        );
        assert_eq!(result.status.code(), Some(1), "{}", case["name"]);
        assert!(result.stdout.is_empty());
        let actual: Value = serde_json::from_slice(&result.stderr).unwrap();
        let original = &case["error"];
        assert_eq!(actual["kind"], original["kind"]);
        assert_eq!(actual["errno"], original["errno"]);
        assert!(actual["message"].as_str().is_some());
        if let Some(relative) = original["path_relative_hex"].as_str() {
            let expected = temp
                .path()
                .join(std::ffi::OsString::from_vec(unhex(relative)));
            assert_eq!(actual["path_bytes"], json!(expected.as_os_str().as_bytes()));
            let human = run(
                env!("CARGO_BIN_EXE_dbc-generator"),
                &[
                    "compose".as_ref(),
                    source.as_os_str(),
                    filename.as_os_str(),
                    output.as_os_str(),
                ],
            );
            assert_eq!(human.status.code(), Some(1));
            assert!(human.stdout.is_empty());
            assert_eq!(
                human.stderr,
                format!(
                    "FileNotFoundError: {}: No such file or directory (os error 2)\n",
                    expected.display()
                )
                .as_bytes()
            );
        }
        for (capture, key) in [
            ("decode_hex", "decode_bytes"),
            ("encode_hex", "encode_bytes"),
        ] {
            if let Some(expected) = original[capture].as_str() {
                assert_eq!(
                    actual[key],
                    json!(unhex(expected)),
                    "{} {key}",
                    case["name"]
                );
            } else {
                assert!(actual.get(key).is_none(), "unrelated byte payload {key}");
            }
        }
        let observed: std::collections::BTreeMap<_, _> = fs::read_dir(&output)
            .unwrap()
            .map(|e| {
                let e = e.unwrap();
                (
                    e.file_name()
                        .as_bytes()
                        .iter()
                        .map(|v| format!("{v:02x}"))
                        .collect::<String>(),
                    fs::read(e.path())
                        .unwrap()
                        .iter()
                        .map(|v| format!("{v:02x}"))
                        .collect::<String>(),
                )
            })
            .collect();
        assert_eq!(
            serde_json::to_value(observed).unwrap(),
            case["outputs"],
            "{}",
            case["name"]
        );
    }
}
#[test]
fn json_errors_is_only_a_leading_flag_and_preserves_usage_help_and_success() {
    let bin = env!("CARGO_BIN_EXE_dbc-generator");
    for tail in [
        vec![],
        vec!["--json-errors"],
        vec!["compose"],
        vec!["unknown"],
    ] {
        let mut args = vec!["--json-errors".as_ref()];
        args.extend(tail.iter().map(std::ffi::OsStr::new));
        let output = run(bin, &args);
        assert_eq!(output.status.code(), Some(2));
        assert!(output.stdout.is_empty());
        let error: Value = serde_json::from_slice(&output.stderr).unwrap();
        assert_eq!(error["kind"], "ArgumentError");
        assert!(error["errno"].is_null());
        for key in ["path_bytes", "decode_bytes", "encode_bytes"] {
            assert!(error.get(key).is_none());
        }
    }
    let ordinary = run(bin, &["--json-errors=bad".as_ref()]);
    assert_eq!(ordinary.status.code(), Some(2));
    assert!(ordinary.stderr.starts_with(b"ArgumentError: "));
    assert!(serde_json::from_slice::<Value>(&ordinary.stderr).is_err());
    let help = success(run(bin, &["--help".as_ref()]));
    assert_eq!(
        success(run(bin, &["--json-errors".as_ref(), "--help".as_ref()])),
        help
    );
    let roster = success(run(bin, &["program-outputs".as_ref()]));
    assert_eq!(
        success(run(
            bin,
            &["--json-errors".as_ref(), "program-outputs".as_ref()]
        )),
        roster
    );
}
