//! Dynamic controller: source policy runs independently; only the probe is a candidate.
#![cfg(feature = "tombstone-tools-native")]
use openpilot_dev_tools::tombstone_reference_check::{self as reference, Command, Options};
use serde_json::{json, Value};
use std::{
    collections::BTreeMap,
    ffi::OsString,
    fs,
    path::{Path, PathBuf},
};
fn repository() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../..")
        .canonicalize()
        .unwrap()
}
fn environment() -> BTreeMap<OsString, OsString> {
    std::env::vars_os().collect()
}
fn native_path(key: &str) -> PathBuf {
    fs::canonicalize(
        std::env::var_os(key)
            .unwrap_or_else(|| panic!("{key} must name the current verified native artifact")),
    )
    .unwrap()
}
#[test]
fn original_three_paths_runner_bytes_and_source_transport_are_explicit() {
    use std::os::unix::ffi::OsStringExt;
    let temp = tempfile::tempdir().unwrap();
    let env = environment();
    let raw = OsString::from_vec(b"runner-\xff".to_vec());
    let args = [
        OsString::from("probe"),
        OsString::from("binding"),
        OsString::from("evidence"),
        OsString::from("/bin/sh"),
        raw.clone(),
    ];
    let Command::Compare(options) = reference::parse(&args, temp.path(), &env).unwrap() else {
        panic!("paths selected source transport")
    };
    assert_eq!(options.binary, temp.path().join("probe"));
    assert_eq!(options.params_binding, temp.path().join("binding"));
    assert_eq!(options.output, temp.path().join("evidence"));
    assert_eq!(options.runner, vec![OsString::from("/bin/sh"), raw]);
    assert!(matches!(
        reference::parse(&["--source".into()], temp.path(), &env).unwrap(),
        Command::Source
    ));
    for count in 0..3 {
        assert!(reference::parse(&args[..count], temp.path(), &env).is_err());
    }
}
#[test]
fn all242_original_scenarios_compare_dynamic_source_candidate_real_files_and_logs() {
    let temp = tempfile::tempdir().unwrap();
    let options = Options {
        binary: native_path("TOMBSTONE_PROBE_BINARY"),
        params_binding: native_path("TOMBSTONE_PARAMS_BINDING"),
        runner: vec![],
        output: temp.path().join("reference"),
        environment: environment(),
    };
    let report: openpilot_log_format::JsonValue = reference::run(&repository(), &options).unwrap();
    let value: Value = serde_json::from_str(&report.to_json().unwrap()).unwrap();
    assert_eq!(value["result"], "PASS");
    assert_eq!(value["comparisons"], 242);
    assert_eq!(value["matching_comparisons"], 242);
    assert_eq!(value["divergences"], json!([]));
    assert_eq!(
        value["counts"],
        json!({"gates":50,"files":33,"scan":6,"reporting-loop":7,"disabled-loop":7,"text":134,"subprocess":5})
    );
    assert_eq!(
        fs::read_to_string(options.output.join("manifest.json")).unwrap(),
        format!("{}\n", reference::format_report(&report).unwrap())
    );
    for (name, count) in [
        ("gates", 50),
        ("files", 33),
        ("scan", 6),
        ("reporting-loop", 7),
        ("disabled-loop", 7),
        ("text", 134),
        ("subprocess", 5),
    ] {
        let rows = fs::read_to_string(options.output.join(name).join("comparisons.jsonl")).unwrap();
        assert_eq!(rows.lines().count(), count, "{name}");
        // Compare the full request roster against the unchanged original capture,
        // not just the count or a schedule generated by the new implementation.
        let capture: Value = serde_json::from_slice(&fs::read(repository().join(
            format!("rust/crates/dev-tools/tests/fixtures/tombstone-tools/stateful-{name}-original.json")
        )).unwrap()).unwrap();
        let original = capture["cases"].as_array().unwrap();
        assert_eq!(original.len(), count);
        for (raw, original) in rows.lines().zip(original) {
            let row = openpilot_log_format::JsonValue::parse(raw).unwrap();
            let mut request: Value =
                serde_json::from_str(&row.get("request").unwrap().to_json().unwrap()).unwrap();
            if name == "scan" && request["op"] == "scan" {
                let path = request["path"].as_str().unwrap();
                request["path"] = Value::String(if path.ends_with("/shared/absent") {
                    "$SHARED/absent".into()
                } else {
                    assert!(
                        path.ends_with("/shared"),
                        "unexpected shared scan path: {path}"
                    );
                    "$SHARED".into()
                });
            }
            let expected_request: Value =
                serde_json::from_str(original["request"].as_str().unwrap()).unwrap();
            assert_eq!(
                request, expected_request,
                "{name} original request {}",
                original["index"]
            );
            assert!(
                row.get("passed").is_some_and(|value| matches!(
                    value.view(),
                    openpilot_log_format::JsonView::Bool(true)
                )),
                "{name}: {raw}"
            );
        }
        assert!(options.output.join(name).join("source.stderr").is_file());
        assert!(options.output.join(name).join("native.stderr").is_file());
    }
}

#[test]
fn invalid_source_removes_prior_success_before_preflight() {
    let root = tempfile::tempdir().unwrap();
    let output = root.path().join("evidence");
    fs::create_dir(&output).unwrap();
    let manifest = output.join("manifest.json");
    fs::write(&manifest, b"{\"result\":\"PASS\"}\n").unwrap();
    let options = Options {
        binary: root.path().join("must-not-execute"),
        params_binding: root.path().join("binding"),
        output,
        runner: vec![],
        environment: environment(),
    };
    assert!(reference::run(root.path(), &options).is_err());
    assert!(
        !manifest.exists(),
        "source failure retained an old success receipt"
    );
}
