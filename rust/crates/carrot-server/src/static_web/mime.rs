use std::path::Path;

pub(crate) fn content_type(path: &Path) -> &'static str {
    let extension = path
        .extension()
        .and_then(|extension| extension.to_str())
        .unwrap_or("")
        .to_ascii_lowercase();
    match extension.as_str() {
        "js" | "mjs" => "text/javascript",
        "json" => "application/json",
        "webmanifest" => "application/manifest+json",
        "doc" | "dot" | "wiz" => "application/msword",
        "nq" => "application/n-quads",
        "nt" => "application/n-triples",
        "oda" => "application/oda",
        "pdf" => "application/pdf",
        "p7c" => "application/pkcs7-mime",
        "ps" | "ai" | "eps" => "application/postscript",
        "trig" => "application/trig",
        "m3u" | "m3u8" => "application/vnd.apple.mpegurl",
        "xls" | "xlb" => "application/vnd.ms-excel",
        "ppt" | "pot" | "ppa" | "pps" | "pwz" => "application/vnd.ms-powerpoint",
        "wasm" => "application/wasm",
        "bcpio" => "application/x-bcpio",
        "cpio" => "application/x-cpio",
        "csh" => "application/x-csh",
        "dvi" => "application/x-dvi",
        "gtar" => "application/x-gtar",
        "hdf" => "application/x-hdf",
        "h5" => "application/x-hdf5",
        "latex" => "application/x-latex",
        "mif" => "application/x-mif",
        "cdf" | "nc" => "application/x-netcdf",
        "p12" | "pfx" => "application/x-pkcs12",
        "ram" => "application/x-pn-realaudio",
        "pyc" | "pyo" => "application/x-python-code",
        "sh" => "application/x-sh",
        "shar" => "application/x-shar",
        "swf" => "application/x-shockwave-flash",
        "sv4cpio" => "application/x-sv4cpio",
        "sv4crc" => "application/x-sv4crc",
        "tar" => "application/x-tar",
        "tcl" => "application/x-tcl",
        "tex" => "application/x-tex",
        "texi" | "texinfo" => "application/x-texinfo",
        "roff" | "t" | "tr" => "application/x-troff",
        "man" => "application/x-troff-man",
        "me" => "application/x-troff-me",
        "ms" => "application/x-troff-ms",
        "ustar" => "application/x-ustar",
        "src" => "application/x-wais-source",
        "xsl" | "rdf" | "wsdl" | "xpdl" => "application/xml",
        "zip" => "application/zip",
        "3gp" | "3gpp" => "audio/3gpp",
        "3g2" | "3gpp2" => "audio/3gpp2",
        "aac" | "adts" | "loas" | "ass" => "audio/aac",
        "au" | "snd" => "audio/basic",
        "mp3" | "mp2" => "audio/mpeg",
        "opus" => "audio/opus",
        "aif" | "aifc" | "aiff" => "audio/x-aiff",
        "ra" => "audio/x-pn-realaudio",
        "wav" => "audio/x-wav",
        "avif" => "image/avif",
        "bmp" => "image/bmp",
        "gif" => "image/gif",
        "ief" => "image/ief",
        "jpg" | "jpe" | "jpeg" => "image/jpeg",
        "heic" => "image/heic",
        "heif" => "image/heif",
        "png" => "image/png",
        "svg" => "image/svg+xml",
        "tiff" | "tif" => "image/tiff",
        "ico" => "image/vnd.microsoft.icon",
        "ras" => "image/x-cmu-raster",
        "pnm" => "image/x-portable-anymap",
        "pbm" => "image/x-portable-bitmap",
        "pgm" => "image/x-portable-graymap",
        "ppm" => "image/x-portable-pixmap",
        "rgb" => "image/x-rgb",
        "xbm" => "image/x-xbitmap",
        "xpm" => "image/x-xpixmap",
        "xwd" => "image/x-xwindowdump",
        "eml" | "mht" | "mhtml" | "nws" => "message/rfc822",
        "css" => "text/css",
        "csv" => "text/csv",
        "html" | "htm" => "text/html",
        "n3" => "text/n3",
        "txt" | "bat" | "c" | "h" | "ksh" | "pl" | "srt" => "text/plain",
        "rtx" => "text/richtext",
        "tsv" => "text/tab-separated-values",
        "vtt" => "text/vtt",
        "py" => "text/x-python",
        "etx" => "text/x-setext",
        "sgm" | "sgml" => "text/x-sgml",
        "vcf" => "text/x-vcard",
        "xml" => "text/xml",
        "mp4" => "video/mp4",
        "mpeg" | "m1v" | "mpa" | "mpe" | "mpg" => "video/mpeg",
        "mov" | "qt" => "video/quicktime",
        "webm" => "video/webm",
        "avi" => "video/x-msvideo",
        "movie" => "video/x-sgi-movie",
        "gz" | "tgz" | "taz" | "tz" | "svgz" => "application/gzip",
        "br" => "application/x-brotli",
        "bz2" | "tbz2" => "application/x-bzip2",
        "xz" | "txz" => "application/x-xz",
        _ => "application/octet-stream",
    }
}
