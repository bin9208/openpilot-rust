pub fn line_times(plan: &[[f32; 15]; 33]) -> [f64; 33] {
    let mut times = [10.0; 33];
    times[0] = 0.0;
    for x in 1..33 {
        let mut t = 0;
        while t < 32 && f64::from(plan[t + 1][0]) < DISTANCE[x] {
            t += 1;
        }
        if t == 32 {
            break;
        }
        let dx = f64::from(plan[t + 1][0]) - f64::from(plan[t][0]);
        times[x] = if dx <= 1e-9 {
            TIME[t]
        } else {
            let fraction = ((DISTANCE[x] - f64::from(plan[t][0])) / dx).clamp(0.0, 1.0);
            fraction * TIME[t + 1] + (1.0 - fraction) * TIME[t]
        };
        if times[x].is_nan() {
            times[x] = 10.0;
        }
    }
    for i in 1..33 {
        if times[i] < times[i - 1] {
            times[i] = times[i - 1];
        }
    }
    times
}
