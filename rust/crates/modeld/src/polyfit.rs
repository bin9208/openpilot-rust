pub fn path_coefficients(plan: &[[f32; 15]; 33]) -> [[f64; 5]; 3] {
    if plan
        .iter()
        .any(|row| row[..3].iter().any(|value| value.is_infinite()))
    {
        return [[f64::NAN; 5]; 3];
    }
    std::array::from_fn(|axis| {
        if plan.iter().any(|row| !row[axis].is_finite()) {
            [f64::NAN; 5]
        } else {
            std::array::from_fn(|degree| {
                FIT[degree]
                    .iter()
                    .zip(plan)
                    .map(|(&coefficient, row)| coefficient * f64::from(row[axis]))
                    .sum()
            })
        }
    })
}
